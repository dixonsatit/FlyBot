"""Write firmware/stackchan/src/robot_cert.h (gitignored) from the robot's mTLS identity:
certs/robot.crt (the client certificate Cloudflare signed for certs/robot.csr) and
certs/robot.key. Without that header the firmware is built with no client certificate.

    python tools/make_robot_cert.py            # after saving the certificate as certs/robot.crt
"""
import pathlib
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "stackchan"
crt, key = root / "certs" / "robot.crt", root / "certs" / "robot.key"
if not crt.exists() or not key.exists():
    sys.exit(f"need {crt} and {key}")
# the certificate must belong to this key
pub = lambda args: subprocess.run(["openssl", *args], check=True, capture_output=True).stdout
if pub(["x509", "-in", str(crt), "-noout", "-pubkey"]) != pub(["pkey", "-in", str(key), "-pubout"]):
    sys.exit("robot.crt was not issued for robot.key")
lit = lambda text: "\n".join(f'    "{line}\\n"' for line in text.strip().splitlines())
(root / "src" / "robot_cert.h").write_text(
    "// Generated by tools/make_robot_cert.py: the robot's mTLS client certificate and key. Never commit.\n"
    "#pragma once\n\n"
    f"static const char ROBOT_CLIENT_CERT[] =\n{lit(crt.read_text())};\n\n"
    f"static const char ROBOT_CLIENT_KEY[] =\n{lit(key.read_text())};\n")
print("wrote", root / "src" / "robot_cert.h")
